# Раздел «Сценарии»: живые ситуации, каждая ссылается на статьи о функциях (rel).

def sbody(pain, steps_list, example=None, more=(), shot=None, extra=''):
    """Сценарий: ситуация → шаги → до/после → что ещё поможет."""
    out = f'<h2>Ситуация</h2><p>{pain}</p><h2>Что сделать</h2>{steps(steps_list, shot)}'
    if example:
        out += f'<h2>Что получится</h2>{example}'
    out += extra
    if more:
        out += '<h2>Что ещё поможет</h2><ul class="ticks">' + ''.join(f'<li>{m}</li>' for m in more) + '</ul>'
    return out


